def _describe_target() -> tuple[str, str] | None:
    """``(provider, model)`` for descriptions.

    ``BRAIN_DESCRIBE_PROVIDER`` / ``BRAIN_DESCRIBE_MODEL`` override the
    summarizer's router. A provider override that differs from the
    summarizer's needs its model named too: ``BRAIN_LLM_MODEL`` belongs to
    the summarizer's provider and a silent default model is never chosen.
    """
    summarizer = _select_provider()
    provider = (os.environ.get("BRAIN_DESCRIBE_PROVIDER") or "").strip().lower() or summarizer
    if provider is None:
        return None
    if provider not in _VALID_PROVIDERS:
        _LOG.warning("BRAIN_DESCRIBE_PROVIDER=%r is not one of %s — describe disabled",
                     provider, ", ".join(sorted(_VALID_PROVIDERS)))
        return None
    model = (os.environ.get("BRAIN_DESCRIBE_MODEL") or "").strip()
    if model:
        return provider, model
    if provider != summarizer:
        _LOG.warning("BRAIN_DESCRIBE_PROVIDER=%s needs BRAIN_DESCRIBE_MODEL — describe "
                     "disabled", provider)
        return None
    return provider, _select_model(provider)


def describe_model() -> str:
    target = _describe_target()
    return "" if target is None else f"{target[0]}/{target[1]}"


def _retrieve(
    paths: VaultPaths,
    queries: list[tuple[str, set[str]]],
) -> list[list[Chunk]]:
    """Every chunk of each query's OWN sources, scored against the query, best first.

    Each query is ``(name, allowed_sources)``; only chunks whose
    ``source_relative_path`` is in ``allowed_sources`` are returned, so a
    concept whose own sources produced no embeddable chunks lands empty
    (and is skipped) instead of borrowing text from unrelated documents,
    honouring the "grounded ONLY in the concept's own sources" contract.
    Per-source selection is the caller's (``_pick_excerpts``).

    Returns a list aligned with ``queries`` (empty lists when the index is
    missing) — callers treat a fully-empty result as "no index".
    """
    empty: list[list[Chunk]] = [[] for _ in queries]
    vectors_path = paths.metadata / "embeddings.npy"
    meta_path = paths.metadata / "embeddings_meta.jsonl"
    if not queries or not vectors_path.exists() or not meta_path.exists():
        return empty
    try:
        import numpy as np
    except ImportError:
        return empty
    from .semantic import _load_embedder, _query_prefix

    # A torn/corrupt index must degrade to empty (mirroring
    # connections.concept_vectors_from_embeddings), not abort the run with a
    # raw traceback — the CLI --describe-concepts path has no outer catch.
    try:
        vectors = np.load(vectors_path)
        with meta_path.open("r", encoding="utf-8", errors="replace") as fh:
            meta = [json.loads(ln) for ln in fh if ln.strip()]
    except (OSError, ValueError, EOFError):
        return empty
    if len(meta) != vectors.shape[0]:
        return empty
    try:
        model, _ = _load_embedder()
    except Exception:  # noqa: BLE001
        return empty

    row_sources = [str(m.get("source_relative_path", "")) for m in meta]
    prefix = _query_prefix()  # BGE retrieval instruction (query-side, see semantic)
    q_vectors = np.asarray(
        model.encode([prefix + q for q, _ in queries],
                     normalize_embeddings=True, show_progress_bar=False),
        dtype=np.float32,
    )
    scores = vectors @ q_vectors.T  # (n_chunks, n_queries)
    out: list[list[Chunk]] = []
    for j, (_name, allowed) in enumerate(queries):
        rows = [i for i, s in enumerate(row_sources) if s in allowed]
        rows.sort(key=lambda i: (-float(scores[i, j]), i))
        out.append([
            (row_sources[i], float(scores[i, j]), str(meta[i].get("text", "")))
            for i in rows
        ])
    return out


def describe_concept(
    name: str,
    excerpts: Sequence[Excerpt],
    *,
    prior: str | None = None,
    max_tokens: int = _MAX_TOKENS,
    logger: logging.Logger | None = None,
) -> ConceptDescription | None:
    """Generate a grounded description, or ``None`` if there's nothing to ground in.

    With ``prior`` (the previous synthesis, citations in this run's source
    numbers) the LLM revises it with ``excerpts`` instead of starting over.
    """
    ctx = [e for e in excerpts if e.text.strip()]
    if not ctx:
        return None  # honest: no sources retrieved -> don't invent
    target = _describe_target()
    if target is None:
        return None
    fenced = "\n\n".join(_fence(f'source="{e.source_id}"', e.text) for e in ctx)
    if prior:
        user = (
            f"Concept: {name}\n\n"
            "Prior synthesis:\n\n" + _fence('kind="prior-synthesis"', prior)
            + "\n\nNew or changed source excerpts from the vault:\n\n" + fenced
            + "\n\n" + _REVISE_TASK
        )
    else:
        user = (
            f"Concept: {name}\n\n"
            "Source excerpts from the vault (use ONLY these):\n\n" + fenced
        )
    result = generate_structured(
        system=_DESCRIBE_SYSTEM,
        user=user,
        schema=ConceptDescription,
        max_tokens=max_tokens,
        logger=logger,
        provider=target[0],
        model=target[1],
    )
    return result if isinstance(result, ConceptDescription) else None


def _refresh_concept(
    note_text: str,
    *,
    name: str,
    current: Mapping[str, str],
    links: Mapping[str, str],
    chunks: Sequence[Chunk],
    model: str,
    logger: logging.Logger,
) -> tuple[_Outcome, str | None]:
    """One stale concept: ``(outcome, new AI-zone body or None)``.

    ``current`` maps each source path to its ``path@source_hash`` key and
    ``links`` each path to its rendered wikilink.
    """
    ids = {p: i for i, p in enumerate(sorted(current), 1)}
    pairs = {p: source_pair(p, keyed) for p, keyed in current.items()}
    recorded = recorded_sources(note_text)
    body = _zone_body(note_text)
    prior: str | None = None
    pending: list[str] = []
    if recorded is not None and body is not None:
        present = {pair[:8] for pair in pairs.values()}
        removed = any(ph not in present for ph in recorded)
        pending = [p for p in sorted(current) if recorded.get(pairs[p][:8]) != pairs[p][9:]]
        # Removed source, or stale with nothing new (model/prompt change): rebuild.
        if not removed and pending:
            prior = _prior_synthesis(body, {links[p]: ids[p] for p in current}) or None
    if prior is None:
        picked, deferred = _pick_excerpts(
            chunks, current.keys(), per_source=1, max_sources=_FIRST_BUILD_SOURCES
        )
    else:
        picked, deferred = _pick_excerpts(
            chunks, pending, per_source=_REVISE_CHUNKS_PER_SOURCE,
            max_sources=_REVISE_SOURCES,
        )
    if deferred:
        logger.info("describe: %s — %d source(s) deferred to a later run", name, len(deferred))
    # Deferred sources stay unrecorded (and out of the hash): the concept
    # stays stale and the next run integrates them.
    covered = [p for p in sorted(current) if p not in deferred]
    want = source_set_hash([current[p] for p in covered], model)
    record = [pairs[p] for p in covered]
    if not picked:
        if prior is None or body is None:
            return "no_context", None
        # New sources without searchable text: record them, keep the synthesis.
        kept = _COMMENT_RE.sub("", body).strip()
        return "restamped", "\n".join([*_header(want, model, record), "", kept])
    excerpts = [Excerpt(ids[p], t) for p, texts in picked.items() for t in texts]
    desc = describe_concept(name, excerpts, prior=prior, logger=logger)
    if desc is None:
        return "failed", None
    # Citable: the sources shown this run, plus those the prior cites.
    shown = {ids[p] for p in picked}
    if prior is not None:
        shown.update(_cited_ids([prior], ids.values()))
    zone = render_ai_zone_body(
        desc, source_hash=want, model=model, recorded=record,
        citations={ids[p]: links[p] for p in current if ids[p] in shown},
        known=ids.values(),
    )
    zone, _n = redact_secrets(zone, profile="note")
    return "generated", zone


def rebuild_descriptions(
    paths: VaultPaths,
    *,
    logger: logging.Logger,
    limit: int | None = None,
    force: bool = False,
    min_sources: int = DEFAULT_MIN_SOURCES,
) -> DescribeStats:
    """Generate/refresh AI descriptions for concepts whose sources changed.

    Unattended: regenerates every stale concept with at least ``min_sources``
    sources (no approval). ``limit`` bounds the number refreshed per run (cost
    control), taking the stale concepts with the most sources first, then by
    slug; ``force`` ignores the cache.
    """
    target = _describe_target()
    if target is None:
        logger.warning("describe: no LLM provider configured — skipping")
        return DescribeStats(no_llm=True)

    concepts_dir = paths.knowledge / "concepts"
    if not concepts_dir.is_dir():
        return DescribeStats()

    model = f"{target[0]}/{target[1]}"
    # Include curated knowledge notes as sources, exactly like concepts.py /
    # connections.py do — otherwise curated-only concepts never get a
    # description and mixed concepts' cache keys ignore curated sources.
    records: list[IndexRecord] = (
        list(latest_records_by_path(paths.metadata_index_jsonl).values())
        + knowledge_records(paths)
    )
    sources = _concept_sources(records)
    displays = _concept_displays(records)
    by_path = {r.relative_path: r for r in records}
    # Key each source on its content hash so a re-ingested revision (same
    # path, new source_hash) reads as a changed source.
    keyed = {p: f"{p}@{r.source_hash or ''}" for p, r in by_path.items()}

    todo: list[str] = []
    skipped_uptodate = 0
    for slug in sorted(sources):
        if len(sources[slug]) < min_sources:
            continue
        note = concepts_dir / f"{slug}.md"
        if not note.exists():
            continue
        want = source_set_hash([keyed[p] for p in sources[slug]], model)
        if not force and existing_description_hash(note.read_text(encoding="utf-8")) == want:
            skipped_uptodate += 1
            continue
        todo.append(slug)
    todo.sort(key=lambda s: (-len(sources[s]), s))
    left_stale = 0
    removed = 0
    if limit is not None and len(todo) > limit:
        left_stale = len(todo) - limit
        todo = todo[:limit]
        logger.info("describe: %d stale concept(s) left for a later run", left_stale)
    if not todo:
        return DescribeStats(skipped_uptodate=skipped_uptodate, left_stale=left_stale)

    queries = [(displays.get(slug, slug), set(sources[slug])) for slug in todo]
    retrieved = _retrieve(paths, queries)
    if all(not v for v in retrieved):
        logger.warning("describe: no usable search index — run --rebuild-search-index")
        return DescribeStats(
            skipped_uptodate=skipped_uptodate, left_stale=left_stale, no_index=True
        )

    counts: dict[_Outcome, int] = {
        "generated": 0, "restamped": 0, "no_context": 0, "failed": 0,
    }
    def read_or_skip(note: Path, slug: str) -> str | None:
        # Orphan removal by a concurrent reindex can delete the note at any
        # point after the stale scan, so every read here tolerates it.
        nonlocal removed
        try:
            return note.read_text(encoding="utf-8")
        except FileNotFoundError:
            removed += 1
            logger.info("describe: %s removed during the run — skipped", slug)
            return None

    for slug, chunks in zip(todo, retrieved, strict=True):
        note = concepts_dir / f"{slug}.md"
        before = read_or_skip(note, slug)
        if before is None:
            continue
        outcome, zone = _refresh_concept(
            before,
            name=displays.get(slug, slug),
            current={p: keyed[p] for p in sources[slug]},
            links={p: index_note_wikilink(by_path[p]) for p in sources[slug]},
            chunks=chunks,
            model=model,
            logger=logger,
        )
        if zone is not None:
            # Splice into the note as it is NOW: a concurrent reindex may
            # have rewritten it during the call.
            now = read_or_skip(note, slug)
            if now is None:
                continue
            _atomic_write(note, upsert_ai_zone(now, zone))
        counts[outcome] += 1
        logger.info("describe: %s %s (%d source(s))", outcome, slug, len(sources[slug]))
    return DescribeStats(
        generated=counts["generated"],
        skipped_uptodate=skipped_uptodate,
        # Restamped = only text-less new sources: recorded, nothing to say.
        skipped_no_context=counts["no_context"] + counts["restamped"],
        # We HAD context but generation returned nothing — an LLM/provider
        # failure, not an empty vault; counted apart so an outage isn't
        # misreported as "no context".
        failed=counts["failed"],
        left_stale=left_stale,
        removed=removed,
    )
