"""Source-grounded concept descriptions that compound across runs.

Each concept note gets a synthesized description — a short summary, a detailed
explanation, and key definitions — generated by the LLM from the *retrieved*
text of the concept's own sources (RAG), never from nothing.

The description lives in a dedicated **AI zone** delimited by
``<!-- AI-GENERATED-START/END -->``, which sits *below* the
``AUTO-GENERATED-END`` marker. That placement means ``concepts.py`` already
preserves it across concept rebuilds (it's part of the preserved tail) with no
changes to that module. The AI zone carries an ``ai-hash`` comment keyed on the
sources it covers + model + prompt version; regeneration is skipped when the
hash is unchanged, so a re-run with unchanged sources costs nothing (idempotent)
and generation is unattended — no human approval step.

The zone also records which sources it was built from (``ai-sources``: one
``<sha(path)[:8]>:<sha(path@source_hash)[:8]>`` pair per source). A refresh
with only added or changed sources REVISES the prior synthesis with just their
excerpts; a removed source, a model or prompt change, or no usable record
rebuilds from scratch. Sources that did not fit a run's cap stay unrecorded,
so the concept stays stale and the next run integrates them.

The LLM cites sources by excerpt number; the wikilinks are built here from the
concept's own source list, and every LLM field is stripped of comments, zone
markers and wikilinks before it is written.
"""
