def source_set_hash(
    sources: Sequence[str], model: str, *, prompt_version: str = _PROMPT_VERSION
) -> str:
    """Cache key: changes when the source set, model, or prompt changes."""
    payload = "\n".join(sorted(set(sources))) + f"\n::{model}::{prompt_version}"
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def _h8(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:8]


def source_pair(path: str, keyed: str) -> str:
    """The recorded ``<sha(path)>:<sha(path@source_hash)>`` pair for one source."""
    return f"{_h8(path)}:{_h8(keyed)}"


def _header(source_hash: str, model: str, recorded: Sequence[str]) -> list[str]:
    lines = [f"<!-- ai-hash: {source_hash} · model: {model} -->"]
    if recorded:
        lines.append(f"<!-- ai-sources: {' '.join(sorted(recorded))} -->")
    return lines


def _clean(text: str) -> str:
    """LLM text minus comments, zone markers, wikilinks (links are ours) and
    stray ``[[``/``]]``, repeated until stable: removing one token can join
    its neighbours into a new one."""
    prev = None
    while text != prev:
        prev = text
        text = _MARKER_RE.sub("", _COMMENT_RE.sub("", text))
        text = _WIKILINK_RE.sub(lambda m: m.group(2) or m.group(1), text)
        text = _BRACKETS_RE.sub("", text)
    return text.strip()


def _run_ids(run: str, known: Collection[int]) -> list[int]:
    """The ``known`` ids one citation run cites, in order (a range covers the
    known ids it spans)."""
    ids: list[int] = []
    for m in _CITE_PART_RE.finditer(run):
        a, b = int(m.group(1)), int(m.group(2) or m.group(1))
        for i in sorted(k for k in known if min(a, b) <= k <= max(a, b)):
            if i not in ids:
                ids.append(i)
    return ids


def _is_citation(group: str, known: Collection[int]) -> bool:
    """A bracket group cites only if every number and range endpoint is a
    ``known`` id and no range spans more ids than are known; anything else
    ([2019-2021], [0-10]) is prose."""
    for m in _CITE_PART_RE.finditer(group):
        a, b = int(m.group(1)), int(m.group(2) or m.group(1))
        if a not in known or b not in known or abs(b - a) >= len(known):
            return False
    return True


def _remap_citations(
    text: str, mapping: Mapping[int, int], known: Collection[int] | None = None
) -> str:
    """Renumber citation groups through ``mapping``. A group of ``known`` ids
    (default: ``mapping``'s) none of which map is dropped; any other bracket
    group is prose, kept verbatim."""
    valid = mapping.keys() if known is None else known

    def _sub(m: re.Match[str]) -> str:
        out = ""
        groups = _CITE_GROUP_RE.findall(m.group(2))
        for cites, run in groupby(groups, key=lambda g: _is_citation(g, valid)):
            joined = "".join(run)
            if not cites:
                out += joined
            elif ids := list(dict.fromkeys(mapping[i] for i in _run_ids(joined, mapping))):
                out += f"[{', '.join(map(str, ids))}]"
        return f"{m.group(1)}{out}" if out else ""
    return _CITE_RE.sub(_sub, text)


def _cited_ids(
    texts: Iterable[str], citable: Collection[int], known: Collection[int] | None = None
) -> list[int]:
    """The ``citable`` ids cited across ``texts``, by first appearance; only
    groups of ``known`` ids (default: ``citable``) are citations."""
    valid = citable if known is None else known
    seen: list[int] = []
    for text in texts:
        for m in _CITE_RE.finditer(text):
            for group in _CITE_GROUP_RE.findall(m.group(2)):
                if _is_citation(group, valid):
                    seen += [i for i in _run_ids(group, citable) if i not in seen]
    return seen


def render_ai_zone_body(
    desc: ConceptDescription,
    *,
    source_hash: str,
    model: str,
    recorded: Sequence[str] = (),
    citations: Mapping[int, str] | None = None,
    known: Collection[int] | None = None,
) -> str:
    """The inner body of the AI zone (markers added by ``upsert_ai_zone``).

    ``citations`` maps each source number the LLM was given to its wikilink;
    cited numbers are renumbered by first appearance and listed under
    ``### Sources``. ``known`` is every source number of the run (default:
    ``citations``'s): a citation of a known number not in ``citations`` is
    dropped, a bracket group with any other number is prose, kept verbatim.
    """
    links = citations or {}
    valid = links.keys() if known is None else known
    summary = _clean(desc.short_summary)
    detail = _clean(desc.detailed_explanation)
    defs = [(_clean(d.term), _clean(d.definition)) for d in desc.key_definitions]
    defs = [(t, d) for t, d in defs if t and d]
    order = _cited_ids([summary, detail, *(x for td in defs for x in td)], links, valid)
    renum = {old: k for k, old in enumerate(order, 1)}
    parts = [
        *_header(source_hash, model, recorded),
        "",
        _DISCLAIMER,
        "",
        "## Description",
        "",
        _remap_citations(summary, renum, valid),
        "",
        _remap_citations(detail, renum, valid),
    ]
    if defs:
        parts += ["", "### Key definitions", ""]
        parts += [
            f"- **{_remap_citations(t, renum, valid)}** — {_remap_citations(d, renum, valid)}"
            for t, d in defs
        ]
    if order:
        parts += ["", _SOURCES_HEADING, ""]
        parts += [f"{k}. {links[old]}" for k, old in enumerate(order, 1)]
    return "\n".join(parts)


def _zone_span(note_text: str) -> tuple[int, int] | None:
    """``(start, end)`` of the AI zone (markers included) below AUTO_END, if any."""
    start = note_text.find(_AI_START, max(note_text.find(_AUTO_END), 0))
    if start < 0:
        return None
    end = note_text.find(_AI_END, start)
    return None if end < 0 else (start, end + len(_AI_END))


def _zone_body(note_text: str) -> str | None:
    span = _zone_span(note_text)
    if span is None:
        return None
    return note_text[span[0] + len(_AI_START): span[1] - len(_AI_END)]


def ai_zone_end(note_text: str) -> int | None:
    """Offset just past the AI zone's end marker, or ``None`` without a zone."""
    span = _zone_span(note_text)
    return None if span is None else span[1]


def forged_ai_marker(content: str) -> str | None:
    """The first AI-zone marker or comment key in user content, if any.

    The describe pass owns these: a user section carrying them could forge
    or freeze the synthesis (a fake ``ai-hash`` reads as up to date).
    """
    m = _FORGED_RE.search(content)
    return m.group(0) if m else None


def upsert_ai_zone(note_text: str, ai_body: str) -> str:
    """Insert or replace the AI zone, preserving everything else.

    Replaces an existing zone in place; otherwise inserts it right after the
    ``AUTO-GENERATED-END`` marker (above the user's hand-written notes).
    """
    block = f"{_AI_START}\n{ai_body.strip()}\n{_AI_END}"
    span = _zone_span(note_text)
    if span is not None:
        pre = note_text[: span[0]].rstrip()
        post = note_text[span[1]:].lstrip("\n")
        return f"{pre}\n\n{block}\n\n{post}".rstrip() + "\n"
    if _AUTO_END in note_text:
        i = note_text.index(_AUTO_END) + len(_AUTO_END)
        head = note_text[:i].rstrip()
        tail = note_text[i:].lstrip("\n")
        return f"{head}\n\n{block}\n\n{tail}".rstrip() + "\n"
    return f"{note_text.rstrip()}\n\n{block}\n"


def existing_description_hash(note_text: str) -> str | None:
    """The ``ai-hash`` recorded in the note's AI zone, if any."""
    body = _zone_body(note_text)
    m = _HASH_RE.search(body) if body is not None else None
    return m.group(1) if m else None


def recorded_sources(note_text: str) -> dict[str, str] | None:
    """``{path hash: content hash}`` from the zone's ``ai-sources`` comment."""
    body = _zone_body(note_text)
    m = _SOURCES_RE.search(body) if body is not None else None
    if m is None:
        return None
    pairs = (_PAIR_RE.match(tok) for tok in m.group(1).split())
    return {p.group(1): p.group(2) for p in pairs if p}


def _prior_synthesis(zone_body: str, link_ids: Mapping[str, int]) -> str:
    """The prior zone's prose, its ``[k]`` citations renumbered to this run's
    source numbers through its own ``### Sources`` list (``link_ids`` maps a
    rendered source link to its number)."""
    text = _COMMENT_RE.sub("", zone_body)
    head, sep, tail = text.rpartition(f"\n{_SOURCES_HEADING}\n")
    if not sep:
        head, tail = text, ""
    listed = {int(m.group(1)): m.group(2).strip() for m in _SOURCE_LINE_RE.finditer(tail)}
    old_to_id = {k: link_ids[link] for k, link in listed.items() if link in link_ids}
    lines = [
        ln for ln in head.splitlines()
        if ln.strip() not in (_DISCLAIMER, "## Description")
    ]
    return _remap_citations("\n".join(lines).strip(), old_to_id, listed.keys())


def _pick_excerpts(
    chunks: Sequence[Chunk],
    allowed: Collection[str],
    *,
    per_source: int,
    max_sources: int,
) -> tuple[dict[str, list[str]], list[str]]:
    """Best ``per_source`` chunk texts from each of the top ``max_sources``
    sources in ``allowed`` (ranked by their best chunk). ``chunks`` is
    best-first. Returns ``(path -> texts, deferred paths beyond the cap)``."""
    best: dict[str, list[str]] = {}
    for path, _score, text in chunks:
        if path not in allowed or not text.strip():
            continue
        got = best.setdefault(path, [])
        if len(got) < per_source:
            got.append(text)
    ranked = list(best)  # first-appearance order == best-score order
    return {p: best[p] for p in ranked[:max_sources]}, ranked[max_sources:]


def _fence(label: str, text: str) -> str:
    return f"<excerpt {label}>\n{_EXCERPT_TAG_RE.sub('&lt;', text)}\n</excerpt>"


