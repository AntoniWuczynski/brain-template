"""Open Loops: one generated note listing what is still waiting on someone.

``knowledge/index/Open Loops.md`` (outside the enrichment scan, so it never
feeds back into search or concepts) is rebuilt by ``rebuild_open_loops``
through ``status.write_managed`` (skip-unchanged, hand tail kept). Sections:

1. Proposed decisions — decision records (by path, ``ingest_lib.decisions``)
   with ``status: proposed``.
2. Project next steps — per project/chat, the newest log (by filename date)
   whose last ``## Next`` / ``### Next`` / ``## Open…`` heading has items
   (``Open Loops —`` feature write-ups excluded).
3. Meeting next steps — ``knowledge/meetings`` notes dated within
   ``MEETING_WINDOW_DAYS`` of ``today``: items under a heading inside
   ``## Notes`` that is exactly "Next steps" / "Następne kroki" (any case,
   optional trailing colon; a combined heading such as "Salary and Next
   Steps" is background, not actions), plus non-empty ``## Actions``.
4. Awaiting your approval — the count of ``approved: false`` memory-inbox
   notes, linking ``Memory inbox.base`` (the per-item view).
5. For a human — the newest dream report's ``## For a human``, verbatim.
6. Open questions — the ``## New — …`` / ``## Carried — …`` headings of the
   dream's ``questions.md``.

Blockquotes, fenced code, HTML comments (multi-line too) and checked
``[x]`` items are skipped everywhere; a ``…:`` lead-in item keeps its nested
items;
``archive/`` (transcripts, duplicated meeting extracts) is never read. Every
item carries its source wikilink and date, and ``today`` only selects the
meeting window, so the body is a pure function of the files: a rebuild over
unchanged state is a byte-for-byte no-op.

Single writer: maintain.sh on the server, or by hand::

    uv run python -m ingest_lib.open_loops [--today YYYY-MM-DD] [--dry-run]
"""
from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from datetime import UTC, date, datetime
from pathlib import Path

from .config import VaultPaths, default_paths
from .decisions import DecisionNote, _str, iter_decisions
from .notes import _split_frontmatter
from .status import write_managed

MEETING_WINDOW_DAYS = 45

_TITLE = "Open Loops"
_BANNER = (
    "Auto-generated by `python -m ingest_lib.open_loops` from decision records, "
    "project logs, meeting notes, the memory inbox and the dream pass. "
    "`knowledge/index/` is outside the enrichment scan. Edit below the "
    "**AUTO-GENERATED-END** marker — that survives regeneration."
)
_INBOX_BASE = "knowledge/index/Memory inbox.base"
_QUESTIONS = "knowledge/notes/dreams/questions.md"
_EMPTY = "_(empty)_"
_NONE = "_(none)_"

_DATED_MD_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})\.md$")
_DATE_PREFIX_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})")
_HEADING_RE = re.compile(r"^(#{1,6}) +(.+?)\s*$")
_FENCE_RE = re.compile(r"^\s*(```|~~~)")
_RULE_RE = re.compile(r"^\s*(-{3,}|\*{3,}|_{3,})\s*$")
_ITEM_RE = re.compile(r"^(?:[-*+]|\d+[.)]) +(.*\S)")
_COMMENT_RE = re.compile(r"<!--.*?-->", re.DOTALL)
_CHECKED_RE = re.compile(r"^\[[xX]\](?:\s|$)")
_LOG_NEXT_RE = re.compile(r"^(?:Next|Open)(?![\w-])")
_MEETING_NEXT_RE = re.compile(r"(?:next steps|następne kroki)\s*:?", re.IGNORECASE)
_MEETING_END_RE = re.compile(r"^## (?:Agenda|Decisions|Actions|Links)\s*$")
_QUESTION_RE = re.compile(r"^(?:New|Carried)\b[^—]* — \S")


@dataclass(frozen=True)
class LoopGroup:
    """Items from one source note."""

    source: str  # vault-relative path, no extension (the wikilink target)
    label: str
    date: str
    items: tuple[str, ...]


@dataclass(frozen=True)
class ForHuman:
    source: str
    date: str
    text: str  # the section body, verbatim
    item_count: int


@dataclass(frozen=True)
class OpenLoops:
    proposed: tuple[DecisionNote, ...]
    project_next: tuple[LoopGroup, ...]
    meeting_next: tuple[LoopGroup, ...]
    awaiting_approval: int
    for_human: ForHuman | None
    questions: LoopGroup | None

    @property
    def item_count(self) -> int:
        groups = (*self.project_next, *self.meeting_next)
        return (
            len(self.proposed)
            + sum(len(g.items) for g in groups)
            + self.awaiting_approval
            + (self.for_human.item_count if self.for_human else 0)
            + (len(self.questions.items) if self.questions else 0)
        )


# ---------------------------------------------------------------------------
# markdown scanning (pure)
# ---------------------------------------------------------------------------

def _clean_lines(body: str) -> list[str]:
    """Body lines minus fenced code, blockquotes and HTML comments (outside
    fences only, multi-line too)."""
    out: list[str] = []
    fenced = commented = False
    for line in body.splitlines():
        if commented:
            end = line.find("-->")
            if end < 0:
                continue
            line, commented = line[end + 3:], False
        elif _FENCE_RE.match(line):
            fenced = not fenced
            continue
        if fenced:
            continue
        line = _COMMENT_RE.sub("", line)
        if (start := line.find("<!--")) >= 0:
            line, commented = line[:start], True
        if line.lstrip().startswith(">"):
            continue
        out.append(line.rstrip())
    return out


def _heading(line: str) -> tuple[int, str] | None:
    m = _HEADING_RE.match(line)
    return (len(m.group(1)), m.group(2)) if m else None


def _section(
    lines: list[str], start: int, *, end: re.Pattern[str] | None = None
) -> list[str]:
    """Lines under the heading at ``start``, up to the next heading of the
    same or a higher level, a thematic break, or a line matching ``end``."""
    head = _heading(lines[start])
    level = head[0] if head else 6
    out: list[str] = []
    for line in lines[start + 1:]:
        h = _heading(line)
        if (h and h[0] <= level) or _RULE_RE.match(line) or (end and end.match(line)):
            break
        out.append(line)
    return out


def _items(lines: list[str]) -> tuple[str, ...]:
    """Top-level list items (with their hard-wrapped continuation lines, up to
    a blank line or nested item); paragraphs when the section has no list.
    A lead-in item ending in ``:`` keeps its nested items as indented
    ``  - …`` lines after it; other nested items are dropped. Checked ``[x]`` items and the
    empty-section placeholder are not items; a section whose items are all
    checked has none."""
    parts: list[list[str]] = []
    subs: list[list[list[str]]] = []
    tail: list[str] | None = None  # the item continuation lines extend
    lead = False  # the last top-level item may still take nested items
    has_list = False  # any top-level item, checked or not
    for line in lines:
        if m := _ITEM_RE.match(line):
            tail, lead, has_list = None, False, True
            if not _CHECKED_RE.match(m.group(1)):
                parts.append([m.group(1)])
                subs.append([])
                tail, lead = parts[-1], True
        elif _heading(line):
            tail, lead = None, False
        elif m := _ITEM_RE.match(line.lstrip()):
            tail = None
            if lead and " ".join(parts[-1]).endswith(":") and not _CHECKED_RE.match(m.group(1)):
                subs[-1].append([m.group(1)])
                tail = subs[-1][-1]
        elif not line.strip():
            tail = None
        elif tail is not None:
            tail.append(line.strip())
        elif not line[0].isspace():
            lead = False
    listed = [
        " ".join(p) + "".join(f"\n  - {' '.join(s)}" for s in nested)
        for p, nested in zip(parts, subs, strict=True)
    ]
    if not has_list:
        current: list[str] = []
        for line in [*lines, ""]:
            if (m := _ITEM_RE.match(line.lstrip())) and _CHECKED_RE.match(m.group(1)):
                continue
            if line.strip() and not _heading(line):
                current.append(line.strip())
            elif current:
                listed.append(" ".join(current))
                current = []
    return tuple(i for i in listed if i != _EMPTY)


def _read(path: Path) -> tuple[dict[str, object], list[str]] | None:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    fm, body = _split_frontmatter(text)
    return fm, _clean_lines(body)


def _label(text: str) -> str:
    """Safe as a wikilink alias."""
    return re.sub(r"[\[\]|]", "", text).strip()


def _source(paths: VaultPaths, path: Path) -> str:
    return path.relative_to(paths.root).as_posix().removesuffix(".md")


# ---------------------------------------------------------------------------
# collectors
# ---------------------------------------------------------------------------

def _project_next(paths: VaultPaths) -> list[LoopGroup]:
    groups: list[LoopGroup] = []
    for log_dir in sorted(
        d for kind in ("projects", "chats") for d in (paths.knowledge / kind).glob("*/log")
    ):
        logs = sorted(
            (p for p in log_dir.iterdir() if _DATED_MD_RE.match(p.name)), reverse=True
        )
        group = next((g for p in logs if (g := _log_group(paths, p))), None)
        if group:
            groups.append(group)
    return groups


def _log_group(paths: VaultPaths, path: Path) -> LoopGroup | None:
    """The items under the last Next/Open heading of one log that has any."""
    read = _read(path)
    if read is None:
        return None
    _fm, lines = read
    for i in reversed(range(len(lines))):
        h = _heading(lines[i])
        if not h or h[0] not in (2, 3) or not _LOG_NEXT_RE.match(h[1]):
            continue
        if h[1].startswith("Open Loops"):
            continue
        items = _items(_section(lines, i))
        if items:
            return LoopGroup(
                source=_source(paths, path),
                label=path.parent.parent.name,
                date=path.stem,
                items=items,
            )
    return None


def _meeting_date(fm: dict[str, object], path: Path) -> date | None:
    for raw in (_str(fm.get("date")), path.stem):
        m = _DATE_PREFIX_RE.match(raw or "")
        if m:
            try:
                return date.fromisoformat(m.group(1))
            except ValueError:
                continue
    return None


def _meeting_next(paths: VaultPaths, today: date) -> list[LoopGroup]:
    groups: list[LoopGroup] = []
    for path in sorted((paths.knowledge / "meetings").rglob("*.md")):
        read = _read(path)
        if read is None:
            continue
        fm, lines = read
        when = _meeting_date(fm, path)
        if when is None or abs((today - when).days) > MEETING_WINDOW_DAYS:
            continue
        items: list[str] = []
        in_notes = False
        for i, line in enumerate(lines):
            if line == "## Notes":
                in_notes = True
            elif _MEETING_END_RE.match(line):
                in_notes = False
                if line.startswith("## Actions"):
                    items += _items(_section(lines, i))
            elif in_notes and (h := _heading(line)) and _MEETING_NEXT_RE.fullmatch(h[1]):
                items += _items(_section(lines, i, end=_MEETING_END_RE))
        if items:
            groups.append(LoopGroup(
                source=_source(paths, path),
                label=_label(_str(fm.get("title")) or path.stem),
                date=when.isoformat(),
                items=tuple(items),
            ))
    return groups


def _awaiting_approval(paths: VaultPaths) -> int:
    count = 0
    for path in sorted((paths.knowledge / "assistant" / "inbox").glob("*.md")):
        read = _read(path)
        if read is not None and read[0].get("approved") is False:
            count += 1
    return count


def _for_human(paths: VaultPaths) -> ForHuman | None:
    reports = paths.knowledge / "notes" / "dreams" / "reports"
    dated = sorted(p for p in reports.glob("*.md") if _DATED_MD_RE.match(p.name))
    if not dated:
        return None
    read = _read(dated[-1])
    if read is None:
        return None
    _fm, lines = read
    for i, line in enumerate(lines):
        if line == "## For a human":
            section = _section(lines, i)
            text = "\n".join(section).strip()
            if not text:
                return None
            return ForHuman(
                source=_source(paths, dated[-1]),
                date=dated[-1].stem,
                text=text,
                item_count=len(_items(section)),
            )
    return None


def _questions(paths: VaultPaths) -> LoopGroup | None:
    path = paths.root / _QUESTIONS
    read = _read(path)
    if read is None:
        return None
    fm, lines = read
    items = tuple(
        h[1] for line in lines
        if (h := _heading(line)) and h[0] == 2 and _QUESTION_RE.match(h[1])
    )
    if not items:
        return None
    return LoopGroup(
        source=_source(paths, path),
        label=_label(_str(fm.get("title")) or "Open questions"),
        date=_str(fm.get("dreamed")) or "",
        items=items,
    )


def _by_recency(group: LoopGroup) -> tuple[str, str]:
    return group.date, group.source


def collect(paths: VaultPaths, today: date) -> OpenLoops:
    return OpenLoops(
        proposed=tuple(n for n in iter_decisions(paths) if n.status == "proposed"),
        project_next=tuple(sorted(_project_next(paths), key=_by_recency, reverse=True)),
        meeting_next=tuple(sorted(_meeting_next(paths, today), key=_by_recency, reverse=True)),
        awaiting_approval=_awaiting_approval(paths),
        for_human=_for_human(paths),
        questions=_questions(paths),
    )


# ---------------------------------------------------------------------------
# rendering + write
# ---------------------------------------------------------------------------

def _render_groups(groups: tuple[LoopGroup, ...]) -> list[str]:
    if not groups:
        return [_NONE]
    out: list[str] = []
    for g in groups:
        when = f" — {g.date}" if g.date else ""
        out += [f"### [[{g.source}|{g.label}]]{when}", ""]
        out += [f"- {item}" for item in g.items]
        out.append("")
    return out[:-1]


def render(loops: OpenLoops) -> str:
    lines = [f"{loops.item_count} open item(s).", ""]

    lines += [f"## Proposed decisions ({len(loops.proposed)})", ""]
    lines += [
        f"- [[{n.ref}|{n.file_number:04d} — {_label(n.title)}]] — "
        f"{n.folder_project.split('/')[1]}, {n.date or 'undated'}"
        for n in loops.proposed
    ] or [_NONE]

    project_items = sum(len(g.items) for g in loops.project_next)
    lines += ["", f"## Project next steps ({project_items})", ""]
    lines += ["_Latest log with next steps per project; the heading carries its date._", ""]
    lines += _render_groups(loops.project_next)

    meeting_items = sum(len(g.items) for g in loops.meeting_next)
    lines += ["", f"## Meeting next steps ({meeting_items})", ""]
    lines += [f"_Meetings dated within {MEETING_WINDOW_DAYS} days._", ""]
    lines += _render_groups(loops.meeting_next)

    lines += ["", f"## Awaiting your approval ({loops.awaiting_approval})", ""]
    lines += [
        f"{loops.awaiting_approval} memory-inbox note(s) with `approved: false`: "
        f"[[{_INBOX_BASE}|Memory inbox]]."
    ]

    human = loops.for_human
    lines += ["", f"## For a human ({human.item_count if human else 0})", ""]
    if human:
        lines += [f"From [[{human.source}|dream report {human.date}]]:", "", human.text]
    else:
        lines += [_NONE]

    questions = loops.questions
    lines += ["", f"## Open questions ({len(questions.items) if questions else 0})", ""]
    lines += _render_groups((questions,) if questions else ())
    return "\n".join(lines)


def rebuild_open_loops(paths: VaultPaths, today: date) -> tuple[bool, int]:
    """Regenerate ``knowledge/index/Open Loops.md``. Returns (written,
    item count); written is False when nothing but ``updated:`` would move."""
    loops = collect(paths, today)
    paths.knowledge_index.mkdir(parents=True, exist_ok=True)
    written = write_managed(
        paths.knowledge_index / f"{_TITLE}.md",
        title=_TITLE,
        auto_body=render(loops),
        banner=_BANNER,
    )
    return written, loops.item_count


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m ingest_lib.open_loops",
        description=f"Rebuild knowledge/index/{_TITLE}.md.",
    )
    parser.add_argument(
        "--today",
        type=date.fromisoformat,
        default=datetime.now(tz=UTC).date(),
        help="Date the meeting window is measured from (default: today, UTC).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the generated body instead of writing the note.",
    )
    args = parser.parse_args(argv)
    today: date = args.today
    paths = default_paths()
    if args.dry_run:
        print(render(collect(paths, today)))
        return 0
    written, count = rebuild_open_loops(paths, today)
    print(f"open loops: {count} item(s), note {'written' if written else 'unchanged'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


